// Regenerate with node src/player-build.mjs from packages/openfilm.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

export function playerAudioSource() {
  const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
  const player = read('../studio/ui/src/editor/player.ts')
    .replace("import { SPEED_MAX, SPEED_MIN } from '../lib/playback-speed.ts';", '')
    .replace("'../../../../src/film-doc.mjs'", "'./film-doc.mjs'");
  const speed = read('../studio/ui/src/lib/playback-speed.ts');
  const clock = 'const performance = { now: () => globalThis.window?.filmHost?.now?.() ?? globalThis.performance.now() };';
  return '// Generated from Studio editor/player.ts and lib/playback-speed.ts.\n'
    + '// Regenerate with node src/player-build.mjs. Do not edit this file directly.\n'
    + ts.transpileModule(`${clock}\n${speed}\n${player}`, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: true },
    }).outputText;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('./player-audio.mjs', import.meta.url), playerAudioSource());
}
